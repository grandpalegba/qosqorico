/** Retourne un provider démo par son id */
export function getDemoProviderById(id) {
  return DEMO_PROVIDERS.find(p => p.id === id) || null;
}

/** Retourne les providers démo pour une série donnée */
export function getDemoProvidersForSeries(seriesName) {
  return DEMO_PROVIDERS.filter(p => p.series_name === seriesName);
}

/** Obtenir les questions d'une série (avec fallback) */
export function getQuestionsForSeries(seriesName) {
  return SERIES_QUESTIONS[seriesName] || FALLBACK_QUESTIONS;
}
